'use strict';
const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('native', {
  dataDir: ipcRenderer.sendSync('dataDir'),
  readerMode: true,
  all: store => ipcRenderer.invoke('all', store),
  put: (store, obj) => ipcRenderer.invoke('put', store, obj),
  del: (store, id) => ipcRenderer.invoke('del', store, id),
  loadSettings: () => ipcRenderer.sendSync('loadSettings'),
  saveSettings: txt => ipcRenderer.sendSync('saveSettings', txt),
  openDataDir: () => ipcRenderer.invoke('openDataDir'),
  saveFile: (name, bytes) => ipcRenderer.invoke('saveFile', name, bytes),
  savePdf: name => ipcRenderer.invoke('savePdf', name),
  setAutoStart: on => ipcRenderer.invoke('setAutoStart', on),
  getAutoStart: () => ipcRenderer.sendSync('getAutoStart'),
  setFullscreen: on => ipcRenderer.invoke('setFullscreen', on),
  isFullscreen: () => ipcRenderer.sendSync('isFullscreen'),
  quit: () => ipcRenderer.invoke('quit'),
  folderList: dir => ipcRenderer.invoke('folderList', dir),
  folderRead: (dir, rel) => ipcRenderer.invoke('folderRead', dir, rel),
  folderWrite: (dir, rel, text) => ipcRenderer.invoke('folderWrite', dir, rel, text),
  folderDelete: (dir, rel) => ipcRenderer.invoke('folderDelete', dir, rel),
  pickFolder: () => ipcRenderer.invoke('pickFolder'),
  suggestFolders: () => ipcRenderer.sendSync('suggestFolders'),
  watchFolder: dir => ipcRenderer.send('watchFolder', dir),
  onFolderChange: fn => ipcRenderer.on('folderChanged', () => fn()),
  megaTest: cfg => ipcRenderer.invoke('megaTest', cfg),
  megaSnapshot: cfg => ipcRenderer.invoke('megaSnapshot', cfg),
  megaRead: (cfg, p, v) => ipcRenderer.invoke('megaRead', cfg, p, v),
  megaCommit: (cfg, up, del) => ipcRenderer.invoke('megaCommit', cfg, up, del),
  megaLogout: () => ipcRenderer.invoke('megaLogout'),
  megaDiag: cfg => ipcRenderer.invoke('megaDiag', cfg),
  protect: text => ipcRenderer.sendSync('protect', text),
  unprotect: val => ipcRenderer.sendSync('unprotect', val),
});
